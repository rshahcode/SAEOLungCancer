# Run from any directory: Rscript run_analysis.R INPUT_DIRECTORY OUTPUT_DIRECTORY
# Inputs and generated outputs must remain outside this code-only repository.
args <- commandArgs(trailingOnly=TRUE)
if (length(args)!=2) stop('Usage: Rscript run_analysis.R INPUT_DIRECTORY OUTPUT_DIRECTORY')
script <- sub('^--file=', '', grep('^--file=', commandArgs(), value=TRUE)[1])
code <- dirname(normalizePath(script))
input <- normalizePath(args[1], mustWork=TRUE)
dir.create(args[2], recursive=TRUE, showWarnings=FALSE)
output <- normalizePath(args[2], mustWork=TRUE)
inside <- function(p) p==code || startsWith(p,paste0(code,.Platform$file.sep))
if (inside(input)||inside(output)) stop('Keep input and output directories outside the code repository')
options(digits=17)
source(file.path(code,'standardization.R'))
source(file.path(code,'burden_and_risks.R'))
source(file.path(code,'trends.R'))
read_input <- function(name) read.csv(file.path(input,name),check.names=FALSE,stringsAsFactors=FALSE)
save_result <- function(x,name) write.csv(x,file.path(output,name),row.names=FALSE,na='')
rates <- normalize_rates(read_input('annual_rates.csv'))
validate_rates(rates)
weights <- read_standard(file.path(input,'standard_population.xlsx'))
save_result(weights,'restricted_standard_weights.csv')
annual <- standardize_rates(rates,weights)
save_result(annual,'annual_standardized_rates_all_age_ranges.csv')
save_result(annual[annual$age_range=='15-49',],'annual_standardized_rates_15_49.csv')
save_result(annual[annual$year %in% c(1990,2019,2023),],'endpoint_rates_with_approximate_bounds.csv')
changes <- endpoint_changes(annual)
save_result(changes,'standardized_period_changes.csv')
age_endpoints <- age_specific_endpoints(rates,read_input('source_age_specific_changes.csv'))
save_result(age_endpoints,'S4_five_year_age_specific_endpoints.csv')
numbers <- rbind(read_input('absolute_burden_1.csv'),read_input('absolute_burden_2.csv'))
numbers <- validate_numbers(numbers)
save_result(numbers,'S3_absolute_burden_source_estimates.csv')
save_result(number_changes(numbers),'absolute_burden_period_changes.csv')
save_result(sex_contributions(numbers),'sex_contributions_to_absolute_burden_change.csv')
rv <- do.call(rbind,lapply(c('risk_male.value.csv','risk_female.value.csv','risk_onlyboth.value.csv'),read_input))
rc <- read_input('risk_both.sex.change.csv')
for (fn in c('risk_male.change.csv','risk_female.change.csv')) {
  z<-read_input(fn); m<-match(key(z,c('location','sex','rei')),key(rc,c('location','sex','rei')))
  if(anyNA(m)||any(abs(as.matrix(z[c('val','lower','upper')])-as.matrix(rc[m,c('val','lower','upper')]))>1e-12)) stop('Risk change exports disagree')
}
risk <- risk_tables(rv,rc)
save_result(risk,'S5_risk_attributable_fractions_and_changes.csv')
save_result(risk[risk$change_UI_relation_to_zero=='No source change estimate',],'risk_missing_temporal_records.csv')
trend <- run_trends(annual)
save_result(trend$primary,'primary_eapc_1990_2023.csv')
save_result(trend$sensitivity,'regional_sensitivity_eapc.csv')
save_result(trend$ar1,'ar1_gls_model_sensitivity.csv')
files <- list.files(input,full.names=TRUE)
manifest <- data.frame(file=basename(files),md5=unname(tools::md5sum(files)))
save_result(manifest,'input_checksums.csv')
writeLines(capture.output(sessionInfo()),file.path(output,'R_session_info.txt'))
cat('Completed validated standardization, burden, risk, and exploratory trend analyses.\n')

